import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {loadStudy} from './study-data.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const dataset=loadStudy(resolve(root,process.argv[2]||'study'));
mkdirSync(resolve(root,'generated'),{recursive:true});
writeFileSync(resolve(root,'generated/dataset.js'),'export default '+JSON.stringify(dataset)+';\n');
const assets=Object.fromEntries(['index.html','app.js','app.css','admin.html','admin.js'].map(name=>['/'+name,readFileSync(resolve(root,'static',name),'utf8').replaceAll('__EXCERPT_WORDS__',String(dataset.spec.excerpt_words))]));
writeFileSync(resolve(root,'generated/assets.js'),'export default '+JSON.stringify(assets)+';\n');
console.log(`Verified ${dataset.spec.source_count} banks and ${dataset.spec.sample_count.toLocaleString()} excerpts (${dataset.spec.excerpt_words} words): ${dataset.spec.id}`);
